<#
  Checks PowerShell text generated by Sift's compiler for token injection
  (issue #8). Runs under Windows PowerShell 5.1 and PowerShell 7; the Pascal
  tests (Test.Compiler, TPsInjectionTests) call it once per shell.

  CaseDir holds cases.tsv written by the Pascal side, one line per case:
    id <TAB> sink <TAB> base64(UTF-8 expected value) <TAB> base64(UTF-8 plain value) <TAB> exec
  and per case <id>.v.oneliner.txt / <id>.p.oneliner.txt (optional, the
  "Copy one-liner" text) and <id>.v.export.ps1 / <id>.p.export.ps1 (the
  "Export as PowerShell" file). "v" is the variant value, "p" is the same
  filter with a plain value.

  Checks, per case and per text:
   AST  - zero parse errors; no here-string token; the AST shape equals the
          plain-value shape once each user value is normalized; every user
          value is one string constant equal to the input, or one Base64
          literal that decodes to it; no extra SubExpression / ScriptBlock /
          InvokeMember nodes (implied by equal shapes).
   EXEC - the text runs against a stub Get-WinEvent in this process (the
          one-liner through ScriptBlock::Create, the export as a script
          file); no output line is PWNED; the stub received the value
          unchanged; the expected stub rows come back.
   PROC - (exec = 1) the same through a new process of the shell running
          this checker (the Pascal side runs it in powershell.exe and in
          pwsh.exe): the one-liner with -Command (stub dot-sourced first, as
          when pasted into a console with the stub loaded) and the export
          file run by a -File runner.

  Output file lines: "FAIL <id> <what>: <detail>", "PWNED <id> <form>",
  then "SUMMARY cases=<n> checks=<n> fails=<n> pwned=<n>".
#>
param(
  [Parameter(Mandatory = $true)][string]$CaseDir,
  [Parameter(Mandatory = $true)][string]$Out
)
$ErrorActionPreference = 'Stop'
Set-StrictMode -Off

$Here = Split-Path -Parent $MyInvocation.MyCommand.Path
$Stub = Join-Path $Here 'Stub-GetWinEvent.ps1'
$Runner = Join-Path $Here 'Invoke-Export.ps1'
$Utf8 = New-Object System.Text.UTF8Encoding($false)
$Lines = New-Object System.Collections.Generic.List[string]
$script:Fails = 0
$script:Pwned = 0
$script:Checks = 0

function Fail([string]$Id, [string]$What, [string]$Detail) {
  $script:Fails++
  $d = ($Detail -replace '[\r\n]+', ' ')
  if ($d.Length -gt 300) { $d = $d.Substring(0, 300) + '...' }
  $Lines.Add("FAIL $Id ${What}: $d")
}

function FromB64([string]$S) {
  if ($S -eq '') { return '' }
  return [System.Text.Encoding]::UTF8.GetString([System.Convert]::FromBase64String($S))
}

function Is-TypeExpr($Ast, [string[]]$Names) {
  return ($Ast -is [System.Management.Automation.Language.TypeExpressionAst]) -and
    ($Names -contains $Ast.TypeName.FullName)
}

# A Base64 decode in the exact form Sift emits:
#   [System.Text.Encoding]::UTF8.GetString([System.Convert]::FromBase64String('...'))
# Returns the decoded string, or $null if $Ast is not that form.
function Get-B64Decode($Ast) {
  if (-not ($Ast -is [System.Management.Automation.Language.InvokeMemberExpressionAst])) { return $null }
  if ($Ast.Member.Value -ne 'GetString' -or $null -eq $Ast.Arguments -or $Ast.Arguments.Count -ne 1) { return $null }
  $m = $Ast.Expression
  if (-not ($m -is [System.Management.Automation.Language.MemberExpressionAst]) -or -not $m.Static) { return $null }
  if (-not (Is-TypeExpr $m.Expression @('System.Text.Encoding', 'Text.Encoding'))) { return $null }
  if ($m.Member.Value -ne 'UTF8') { return $null }
  $inner = $Ast.Arguments[0]
  if (-not ($inner -is [System.Management.Automation.Language.InvokeMemberExpressionAst]) -or -not $inner.Static) { return $null }
  if ($inner.Member.Value -ne 'FromBase64String' -or $inner.Arguments.Count -ne 1) { return $null }
  if (-not (Is-TypeExpr $inner.Expression @('System.Convert', 'Convert'))) { return $null }
  $lit = $inner.Arguments[0]
  if (-not ($lit -is [System.Management.Automation.Language.StringConstantExpressionAst])) { return $null }
  try { return (FromB64 $lit.Value) } catch { return $null }
}

# Shape of a script: one token per AST node in visit order. A user value
# (string constant equal to $Value, or a Base64 decode of it, with the
# ( ) wrapper Sift puts around a decode) becomes USERVALUE; any other
# Base64 decode (the query XML) becomes B64BLOB.
function Get-Shape([string]$Text, [string]$Value, [ref]$UserCount, [ref]$Errors, [ref]$HereStrings) {
  $tokens = $null
  $errs = $null
  $ast = [System.Management.Automation.Language.Parser]::ParseInput($Text, [ref]$tokens, [ref]$errs)
  $Errors.Value = @($errs)
  $HereStrings.Value = @($tokens | Where-Object { $_.Kind -eq 'HereStringLiteral' -or $_.Kind -eq 'HereStringExpandable' }).Count
  $all = @($ast.FindAll({ $true }, $true))
  $skip = New-Object 'System.Collections.Generic.HashSet[object]'
  $label = @{}
  foreach ($n in $all) {
    $dec = Get-B64Decode $n
    if ($null -eq $dec) { continue }
    $root = $n
    $tag = 'B64BLOB'
    if ($dec -ceq $Value) {
      $tag = 'USERVALUE'
      $p1 = $n.Parent
      if ($p1 -is [System.Management.Automation.Language.CommandExpressionAst]) {
        $p2 = $p1.Parent
        if (($p2 -is [System.Management.Automation.Language.PipelineAst]) -and $p2.PipelineElements.Count -eq 1) {
          $p3 = $p2.Parent
          if ($p3 -is [System.Management.Automation.Language.ParenExpressionAst]) { $root = $p3 }
        }
      }
    }
    $label[$root] = $tag
    foreach ($d in @($root.FindAll({ $true }, $true))) { if (-not [object]::ReferenceEquals($d, $root)) { [void]$skip.Add($d) } }
  }
  $shape = New-Object System.Collections.Generic.List[string]
  $uc = 0
  foreach ($n in $all) {
    if ($skip.Contains($n)) { continue }
    if ($label.ContainsKey($n)) {
      $shape.Add($label[$n])
      if ($label[$n] -eq 'USERVALUE') { $uc++ }
      continue
    }
    if ($n -is [System.Management.Automation.Language.StringConstantExpressionAst]) {
      if ($n.Value -ceq $Value) { $shape.Add('USERVALUE'); $uc++ }
      else { $shape.Add('SC:' + $n.StringConstantType + ':' + $n.Value) }
    } elseif ($n -is [System.Management.Automation.Language.VariableExpressionAst]) {
      $shape.Add('VAR:' + $n.VariablePath.UserPath)
    } elseif ($n -is [System.Management.Automation.Language.TypeExpressionAst]) {
      $shape.Add('TYPE:' + $n.TypeName.FullName)
    } elseif ($n -is [System.Management.Automation.Language.CommandAst]) {
      $shape.Add('CMD:' + $n.GetCommandName())
    } elseif ($n -is [System.Management.Automation.Language.BinaryExpressionAst]) {
      $shape.Add('BIN:' + $n.Operator)
    } elseif ($n -is [System.Management.Automation.Language.CommandParameterAst]) {
      $shape.Add('PARAM:' + $n.ParameterName)
    } else {
      $shape.Add($n.GetType().Name)
    }
  }
  $UserCount.Value = $uc
  return ($shape -join "`n")
}

function Check-Ast([string]$Id, [string]$Form, [string]$VText, [string]$PText, [string]$Value, [string]$Plain) {
  $script:Checks++
  $uv = 0; $ev = $null; $hv = 0
  $up = 0; $ep = $null; $hp = 0
  $sv = Get-Shape $VText $Value ([ref]$uv) ([ref]$ev) ([ref]$hv)
  $sp = Get-Shape $PText $Plain ([ref]$up) ([ref]$ep) ([ref]$hp)
  if ($ep.Count -gt 0) { Fail $Id "AST/$Form" ('plain baseline has parse errors: ' + $ep[0].Message); return }
  if ($ev.Count -gt 0) { Fail $Id "AST/$Form" ("$($ev.Count) parse error(s): " + $ev[0].Message); return }
  if ($hv -gt 0) { Fail $Id "AST/$Form" "$hv here-string token(s)"; return }
  if ($uv -ne $up) { Fail $Id "AST/$Form" "user value appears $uv time(s) as one literal or Base64 decode, plain baseline $up"; return }
  if ($sv -cne $sp) {
    $a = $sv -split "`n"; $b = $sp -split "`n"
    $i = 0
    while ($i -lt $a.Count -and $i -lt $b.Count -and $a[$i] -ceq $b[$i]) { $i++ }
    $x = if ($i -lt $a.Count) { $a[$i] } else { '<end>' }
    $y = if ($i -lt $b.Count) { $b[$i] } else { '<end>' }
    Fail $Id "AST/$Form" "shape differs from plain baseline at node $i ($x vs $y; $($a.Count) vs $($b.Count) nodes)"
  }
}

function Has-Pwned([string]$Text) {
  foreach ($l in ($Text -split "`r?`n")) { if ($l.Trim() -ceq 'PWNED') { return $true } }
  return $false
}

function Has-Row([string]$Text, [string]$N) {
  return [regex]::IsMatch($Text, "(^|\s)$N(\s|$)", 'Multiline')
}

function Expect-Rows([string]$Id, [string]$Form, [string]$Sink, [string]$Text) {
  $r101 = Has-Row $Text '101'
  $r202 = Has-Row $Text '202'
  switch ($Sink) {
    'msginc' { $ok = $r101 -and -not $r202; $want = '101 only' }
    'repro' { $ok = $r101 -and -not $r202; $want = '101 only' }
    'perpath' { $ok = $r101 -and -not $r202; $want = '101 only' }
    'msgexc' { $ok = $r202 -and -not $r101; $want = '202 only' }
    default { $ok = $r101 -and $r202; $want = '101 and 202' }
  }
  if (-not $ok) { Fail $Id "ROWS/$Form" "expected stub rows $want; got 101=$r101 202=$r202" }
}

function Read-StubLog([string]$Path) {
  $recs = @()
  if (Test-Path -LiteralPath $Path) {
    foreach ($l in [System.IO.File]::ReadAllLines($Path, $Utf8)) {
      if ($l.Trim() -eq '') { continue }
      $recs += ,($l)
    }
  }
  return $recs
}

# Stub log line: key=b64,b64;key=b64 ... (FilterHashtable keys only)
function Check-Received([string]$Id, [string]$Form, [string]$Sink, [string]$Value, [string]$LogPath) {
  $keys = switch ($Sink) { 'provider' { @('ProviderName') } 'logname' { @('LogName') } 'path' { @('Path') } 'user' { @('UserID') } 'repro' { @('LogName', 'ProviderName') } default { @() } }
  foreach ($key in $keys) { Check-ReceivedKey $Id $Form $key $Value $LogPath }
}

function Check-ReceivedKey([string]$Id, [string]$Form, [string]$Key, [string]$Value, [string]$LogPath) {
  $key = $Key
  $seen = $false
  foreach ($rec in (Read-StubLog $LogPath)) {
    foreach ($kv in ($rec -split ';')) {
      $p = $kv.Split('=', 2)
      if ($p.Count -ne 2 -or $p[0] -ne $key) { continue }
      $vals = @($p[1].Split(',') | ForEach-Object { FromB64 $_ })
      $seen = $true
      if ($vals.Count -ne 1 -or -not ($vals[0] -ceq $Value)) {
        Fail $Id "VALUE/$Form" "stub received $key as $($vals.Count) value(s), not the input unchanged"
      }
    }
  }
  if (-not $seen) { Fail $Id "VALUE/$Form" "stub never received $key" }
}

. $Stub

function Exec-InProcess([string]$Id, [string]$Kind, [string]$Sink, [string]$Value, [string]$Text, [string]$File) {
  $script:Checks++
  $log = Join-Path $CaseDir ("stub-" + $PID + ".log")
  if (Test-Path -LiteralPath $log) { Remove-Item -LiteralPath $log -Force }
  $env:SIFT_STUB_LOG = $log
  $env:SIFT_STUB_MSG = [System.Convert]::ToBase64String($Utf8.GetBytes($Value))
  $o = ''
  try {
    if ($File) {
      $o = (& { & $File } *>&1 | Out-String -Width 400)
    } else {
      $sb = [scriptblock]::Create($Text)
      $o = (& { & $sb } *>&1 | Out-String -Width 400)
    }
  } catch {
    $o = 'ERROR: ' + $_.Exception.Message
  }
  if (Has-Pwned $o) { $script:Pwned++; $Lines.Add("PWNED $Id inproc-$Kind"); Fail $Id "EXEC/inproc-$Kind" 'printed PWNED' }
  if ($o.StartsWith('ERROR: ')) { Fail $Id "EXEC/inproc-$Kind" $o; return }
  Expect-Rows $Id "inproc-$Kind" $Sink $o
  if ($Kind -eq 'oneliner') { Check-Received $Id "inproc-$Kind" $Sink $Value $log }
}

function Quote-Arg([string]$S) {
  # CommandLineToArgvW rules: backslashes before a quote are doubled, quotes are \"
  $r = [regex]::Replace($S, '(\\*)"', { param($m) ($m.Groups[1].Value * 2) + '\"' })
  $r = [regex]::Replace($r, '(\\+)$', { param($m) $m.Groups[1].Value * 2 })
  return '"' + $r + '"'
}

function Find-Shell([string]$Name) {
  if ($Name -eq 'pwsh') {
    if ($env:SIFT_PWSH -and (Test-Path -LiteralPath $env:SIFT_PWSH)) { return $env:SIFT_PWSH }
    foreach ($pf in @($env:ProgramW6432, $env:ProgramFiles)) {
      if (-not $pf) { continue }
      $p = Join-Path $pf 'PowerShell\7\pwsh.exe'
      if (Test-Path -LiteralPath $p) { return $p }
    }
    $c = Get-Command pwsh.exe -ErrorAction SilentlyContinue
    if ($c) { return $c.Source }
    return $null
  }
  return (Join-Path $env:SystemRoot 'System32\WindowsPowerShell\v1.0\powershell.exe')
}

function Exec-Process([string]$Id, [string]$Form, [string]$Sink, [string]$Value, [string]$Shell, [string]$ArgLine) {
  $script:Checks++
  $log = Join-Path $CaseDir ("stub-p-" + $PID + ".log")
  if (Test-Path -LiteralPath $log) { Remove-Item -LiteralPath $log -Force }
  $psi = New-Object System.Diagnostics.ProcessStartInfo
  $psi.FileName = $Shell
  $psi.Arguments = $ArgLine
  $psi.UseShellExecute = $false
  $psi.CreateNoWindow = $true
  $psi.RedirectStandardOutput = $true
  $psi.RedirectStandardError = $true
  $psi.EnvironmentVariables['SIFT_STUB_LOG'] = $log
  $psi.EnvironmentVariables['SIFT_STUB_MSG'] = [System.Convert]::ToBase64String($Utf8.GetBytes($Value))
  $p = [System.Diagnostics.Process]::Start($psi)
  $so = $p.StandardOutput.ReadToEndAsync()
  $se = $p.StandardError.ReadToEndAsync()
  if (-not $p.WaitForExit(120000)) { try { $p.Kill() } catch {} ; Fail $Id "PROC/$Form" 'timed out'; return }
  $o = $so.Result + "`n" + $se.Result
  if (Has-Pwned $o) { $script:Pwned++; $Lines.Add("PWNED $Id $Form"); Fail $Id "PROC/$Form" 'printed PWNED' }
  if ($p.ExitCode -ne 0) { Fail $Id "PROC/$Form" ("exit " + $p.ExitCode + ': ' + $se.Result) }
  Expect-Rows $Id "$Form" $Sink $o
  if ($Form -like '*-Command') { Check-Received $Id $Form $Sink $Value $log }
}

$cases = @([System.IO.File]::ReadAllLines((Join-Path $CaseDir 'cases.tsv'), $Utf8) | Where-Object { $_ -ne '' })
$me = if ($PSVersionTable.PSEdition -eq 'Core') { 'pwsh' } else { 'powershell' }
$shells = @(@{ Name = $me; Path = (Find-Shell $me) })
foreach ($s in $shells) {
  if (-not $s.Path -or -not (Test-Path -LiteralPath $s.Path)) { Fail 'setup' 'shell' "$($s.Name) not found (install PowerShell 7 or set SIFT_PWSH)" }
}

foreach ($line in $cases) {
  $f = $line.Split("`t")
  $id = $f[0]; $sink = $f[1]; $value = FromB64 $f[2]; $plain = FromB64 $f[3]; $exec = ($f.Count -gt 4 -and $f[4] -eq '1')
  $vo = Join-Path $CaseDir "$id.v.oneliner.txt"
  $po = Join-Path $CaseDir "$id.p.oneliner.txt"
  $ve = Join-Path $CaseDir "$id.v.export.ps1"
  $pe = Join-Path $CaseDir "$id.p.export.ps1"
  if ((Test-Path -LiteralPath $vo) -ne (Test-Path -LiteralPath $po)) { Fail $id 'FILES' 'one-liner exists for only one of variant / plain'; continue }
  if (Test-Path -LiteralPath $vo) {
    $vt = [System.IO.File]::ReadAllText($vo, $Utf8)
    $pt = [System.IO.File]::ReadAllText($po, $Utf8)
    Check-Ast $id 'oneliner' $vt $pt $value $plain
    Exec-InProcess $id 'oneliner' $sink $value $vt $null
    if ($exec) {
      foreach ($s in $shells) {
        if (-not $s.Path) { continue }
        $cmd = ". " + "'" + $Stub.Replace("'", "''") + "'; " + $vt
        Exec-Process $id "$($s.Name)-Command" $sink $value $s.Path ('-NoProfile -NonInteractive -ExecutionPolicy Bypass -Command ' + (Quote-Arg $cmd))
      }
    }
  }
  if (Test-Path -LiteralPath $ve) {
    # read the file the way a shell does (BOM detection) for the AST check
    $vt = [System.IO.File]::ReadAllText($ve)
    $pt = [System.IO.File]::ReadAllText($pe)
    Check-Ast $id 'export' $vt $pt $value $plain
    Exec-InProcess $id 'export' $sink $value $null $ve
    if ($exec) {
      foreach ($s in $shells) {
        if (-not $s.Path) { continue }
        Exec-Process $id "$($s.Name)-File" $sink $value $s.Path ('-NoProfile -NonInteractive -ExecutionPolicy Bypass -File ' + (Quote-Arg $Runner) + ' ' + (Quote-Arg $ve))
      }
    }
  } else {
    Fail $id 'FILES' 'no export file'
  }
}
$Lines.Add("SUMMARY cases=$($cases.Count) checks=$script:Checks fails=$script:Fails pwned=$script:Pwned")
[System.IO.File]::WriteAllLines($Out, $Lines.ToArray(), $Utf8)
exit 0
